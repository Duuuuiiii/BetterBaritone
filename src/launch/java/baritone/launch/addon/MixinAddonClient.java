package baritone.launch.addon;

import baritone.process.elytra.ElytraKeybinds;
import net.minecraft.client.Minecraft;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Unique;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(Minecraft.class)
public abstract class MixinAddonClient {
    @Unique private final ElytraKeybinds betterBaritone$keys = new ElytraKeybinds();

    @Inject(method = "tick", at = @At("HEAD"))
    private void betterBaritone$tick(CallbackInfo callback) {
        betterBaritone$keys.tick((Minecraft) (Object) this);
    }
}
